import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

import { afterAll, describe, expect, it } from '@jest/globals';

import { API_MODULES_DIR, discoverModules, generateRegistry, REGISTRY_FILE, renderRegistry, run } from './gen-module-registry.js';

const dirs: string[] = [];
afterAll(() => dirs.forEach((dir) => rmSync(dir, { recursive: true, force: true })));

function modulesFixture(files: readonly string[]): string {
  const root = mkdtempSync(join(tmpdir(), 'modules-'));
  dirs.push(root);
  for (const file of files) {
    const path = join(root, ...file.split('/'));
    mkdirSync(join(path, '..'), { recursive: true });
    writeFileSync(path, '');
  }
  return root;
}

describe('module registry discovery (PLAN.md §5 rule 2)', () => {
  it('lists modules with routes.ts or routes/index.ts, sorted, and skips the rest', () => {
    const dir = modulesFixture([
      'quotes/routes.ts',
      'admin-settings/routes/index.ts',
      'audit/service/.gitkeep',
      'orders/routes/orders.routes.ts',
      'stray.ts',
    ]);
    expect(discoverModules(dir)).toEqual(['admin-settings', 'quotes']);
  });

  it('refuses a module folder that is not kebab-case', () => {
    expect(() => discoverModules(modulesFixture(['Bad_Name/routes.ts']))).toThrow('Module folder "Bad_Name" is not kebab-case');
  });

  it('imports each module public index.ts under a camelCase name, with its routeErrors (assertion 6)', () => {
    const source = renderRegistry(['admin-settings', 'quotes']);
    expect(source).toContain(
      "import { httpModule as adminSettingsModule, routeErrors as adminSettingsRouteErrors } from './admin-settings/index.js';",
    );
    expect(source).toContain('= [adminSettingsModule, quotesModule];');
    expect(source).toContain("= {'admin-settings': adminSettingsRouteErrors, 'quotes': quotesRouteErrors};");
    expect(source.split('\n')[0]).toMatch(/^\/\/ Generated by tools\/api\/gen-module-registry\.ts.*Do not edit/);
  });

  it('writes, then reports up to date; --check fails on a stale file without writing', async () => {
    const dir = modulesFixture(['quotes/routes.ts']);
    expect(await run(dir, true)).toMatchObject({ status: 1 });
    expect((await run(dir, false)).message).toMatch(/written$/);
    expect(await run(dir, true)).toMatchObject({ status: 0 });
    writeFileSync(join(dir, REGISTRY_FILE), '// edited by hand\n');
    expect(await run(dir, true)).toMatchObject({ status: 1, message: expect.stringContaining('npm run gen:modules') as unknown });
    expect(readFileSync(join(dir, REGISTRY_FILE), 'utf8')).toBe('// edited by hand\n');
  });

  it('the committed apps/api registry is up to date', async () => {
    expect(readFileSync(join(API_MODULES_DIR, REGISTRY_FILE), 'utf8')).toBe(await generateRegistry(API_MODULES_DIR));
  });
});
