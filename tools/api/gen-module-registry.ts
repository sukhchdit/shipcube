/**
 * Module registry generator (PLAN.md §5 rule 2, TASK-006): no hand-edited central registry. Every API module that
 * declares HTTP routes (`apps/api/src/modules/<module>/routes.ts` or `routes/index.ts`, ARCHITECTURE §module layout)
 * is listed in `apps/api/src/modules/index.generated.ts`, which imports the module's public `index.ts` (its
 * composition root, D-ORCH-006), its `httpModule: ModuleRegistration` export and its `routeErrors: RouteErrors` export
 * (the catalogue codes its services can throw per operation, api/README.md §15 assertion 6; TASK-036). A module with a
 * routes file but without both exports fails the type-check.
 *
 *   tsx tools/api/gen-module-registry.ts           write the registry (run by the api `build` and `npm run gen:modules`)
 *   tsx tools/api/gen-module-registry.ts --check   exit 1 when the committed registry is stale (CI lane A)
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { format, resolveConfig } from 'prettier';

export const REGISTRY_FILE = 'index.generated.ts';
const MODULE_NAME = /^[a-z][a-z0-9-]*$/;

/** Module folders (sorted) that declare HTTP routes. */
export function discoverModules(modulesDir: string): string[] {
  return readdirSync(modulesDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .filter((name) => existsSync(join(modulesDir, name, 'routes.ts')) || existsSync(join(modulesDir, name, 'routes', 'index.ts')))
    .map((name) => {
      if (!MODULE_NAME.test(name)) throw new Error(`Module folder "${name}" is not kebab-case`);
      return name;
    })
    .sort();
}

const camelOf = (module: string): string => module.replace(/-([a-z0-9])/g, (_match, letter: string) => letter.toUpperCase());
const identifierOf = (module: string): string => `${camelOf(module)}Module`;
const routeErrorsOf = (module: string): string => `${camelOf(module)}RouteErrors`;

/** Registry source before formatting. */
export function renderRegistry(modules: readonly string[]): string {
  const imports = modules.map(
    (module) => `import { httpModule as ${identifierOf(module)}, routeErrors as ${routeErrorsOf(module)} } from './${module}/index.js';`,
  );
  return [
    '// Generated by tools/api/gen-module-registry.ts (npm run gen:modules). Do not edit: add a module routes file instead.',
    "import type { ModuleRegistration } from '../app.js';",
    "import type { RouteErrors } from '../platform/routing/define-route.js';",
    ...imports,
    '',
    '/** Every API module with HTTP routes, in name order (PLAN.md §5 rule 2). */',
    `export const moduleRegistry: readonly ModuleRegistration[] = [${modules.map(identifierOf).join(', ')}];`,
    '',
    '/** Per module, the codes its services can throw per operation (api/README.md §15 assertion 6; TASK-036). */',
    `export const moduleRouteErrors: Readonly<Record<string, RouteErrors>> = {${modules.map((module) => `'${module}': ${routeErrorsOf(module)}`).join(', ')}};`,
    '',
  ].join('\n');
}

/** Formatted with the repository Prettier configuration, so `format:check` accepts the generated file. */
export async function generateRegistry(modulesDir: string): Promise<string> {
  const target = join(modulesDir, REGISTRY_FILE);
  const options = (await resolveConfig(target)) ?? {};
  return format(renderRegistry(discoverModules(modulesDir)), { ...options, filepath: target });
}

export interface RunResult {
  readonly status: 0 | 1;
  readonly message: string;
}

export async function run(modulesDir: string, check: boolean): Promise<RunResult> {
  const target = join(modulesDir, REGISTRY_FILE);
  const expected = await generateRegistry(modulesDir);
  const current = existsSync(target) ? readFileSync(target, 'utf8') : undefined;
  const shown = relative(process.cwd(), target).replaceAll('\\', '/');
  if (current === expected) return { status: 0, message: `${shown} is up to date` };
  if (check) return { status: 1, message: `${shown} is stale: run npm run gen:modules and commit the result` };
  writeFileSync(target, expected);
  return { status: 0, message: `${shown} written` };
}

export const API_MODULES_DIR = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..', 'apps', 'api', 'src', 'modules');

async function main(): Promise<number> {
  try {
    const result = await run(API_MODULES_DIR, process.argv.includes('--check'));
    (result.status === 0 ? process.stdout : process.stderr).write(`[gen:modules] ${result.message}\n`);
    return result.status;
  } catch (error) {
    process.stderr.write(`[gen:modules] ${error instanceof Error ? error.message : String(error)}\n`);
    return 1;
  }
}

if (import.meta.main) {
  void main().then((code) => {
    process.exitCode = code;
  });
}
