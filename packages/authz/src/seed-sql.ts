/**
 * Renders the versioned seed migration of the authz tables (REQ-RBAC-002/013, data-model §3.3, §9.2) from the
 * catalogue and the role seed, so the SQL is never hand-typed. Pure: deterministic row IDs come from an injected
 * factory (tools/authz/generate.ts derives them from a hash of the natural key). The statements are plain
 * `INSERT ... VALUES ... ON CONFLICT ("id") DO NOTHING` of new rows (data-changing: no, D-SEC-PR8-01): re-running them
 * adds nothing and widens no role, while a row that collides on its natural key under a different ID raises instead of
 * being silently kept (PR8-SEC-08 (b)).
 */
import type { PermissionDefinition } from './permissions/index.js';
import type { RoleDefinition } from './roles.js';

/** Reserved SYSTEM actor (data-model §1.6): `created_by`/`updated_by` of seed rows. */
export const SYSTEM_ACTOR_ID = '00000000-0000-7000-8000-000000000001';

export type SeedIdKind = 'permission' | 'role' | 'role_permission';
export type SeedIdFactory = (kind: SeedIdKind, naturalKey: string) => string;

export interface SeedMigration {
  readonly up: string;
  readonly down: string;
}

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;

const literal = (value: string): string => `'${value.replaceAll("'", "''")}'`;

/** Natural key of a role-permission link (`<role key>|<permission key>`). */
export const linkKey = (roleKey: string, permissionKey: string): string => `${roleKey}|${permissionKey}`;

function insert(table: string, columns: readonly string[], rows: readonly string[][]): string {
  const header = `INSERT INTO "public"."${table}" (${columns.map((column) => `"${column}"`).join(', ')}) VALUES`;
  return [header, rows.map((row) => `  (${row.join(', ')})`).join(',\n'), 'ON CONFLICT ("id") DO NOTHING;'].join('\n');
}

const keyList = (keys: readonly string[]): string => keys.map(literal).join(',\n  ');

export function renderSeedMigration(
  catalogue: readonly PermissionDefinition[],
  roles: readonly RoleDefinition<string, string>[],
  version: number,
  idFor: SeedIdFactory,
  regenerateCommand: string,
): SeedMigration {
  const id = (kind: SeedIdKind, naturalKey: string): string => {
    const value = idFor(kind, naturalKey);
    if (!UUID.test(value)) throw new Error(`seed id for ${kind} "${naturalKey}" is not a lower-case UUID: "${value}"`);
    return literal(value);
  };
  const actor = literal(SYSTEM_ACTOR_ID);
  const links = roles.flatMap((role) => role.permissions.map((permission) => ({ role: role.key, permission })));
  const generated = `-- GENERATED by \`${regenerateCommand}\` from packages/authz (catalogue version ${String(version)}); do not edit.`;
  const up = [
    '-- migration-kind: expand',
    '-- data-changing: no',
    '-- reversible: yes',
    '--',
    generated,
    `-- Seeds ${String(catalogue.length)} permissions, ${String(roles.length)} roles and ${String(links.length)} role-permission links`,
    '-- (REQ-RBAC-002/003, data-model §3.3, §9.2) into the tables created by the previous migration. Plain INSERT of new',
    '-- rows with deterministic IDs and ON CONFLICT ("id") DO NOTHING: a re-run adds nothing and widens no role',
    '-- (AT-US-066-01). Released seed versions are pinned by SHA-256 and immutable (D-SEC-PR8-01): a catalogue or grant',
    '-- change bumps the version and ships as a new migration.',
    insert(
      'permissions',
      ['id', 'key', 'description', 'category', 'operator_only', 'created_by', 'updated_by'],
      catalogue.map((p) => [
        id('permission', p.key),
        literal(p.key),
        literal(p.description),
        literal(p.category),
        String(p.operatorOnly),
        actor,
        actor,
      ]),
    ),
    insert(
      'roles',
      ['id', 'key', 'name_key', 'scope', 'is_system', 'description', 'created_by', 'updated_by'],
      roles.map((r) => [
        id('role', r.key),
        literal(r.key),
        literal(r.nameKey),
        literal(r.scope),
        'true',
        literal(r.description),
        actor,
        actor,
      ]),
    ),
    insert(
      'role_permissions',
      ['id', 'role_id', 'permission_id', 'created_by', 'updated_by'],
      links.map((link) => [
        id('role_permission', linkKey(link.role, link.permission)),
        id('role', link.role),
        id('permission', link.permission),
        actor,
        actor,
      ]),
    ),
    '',
  ].join('\n');
  const down = [
    `-- Reverts the authz seed of catalogue version ${String(version)}: deletes exactly the seeded rows, links first (data-model §8.4).`,
    generated,
    `DELETE FROM "public"."role_permissions" WHERE "id" IN (\n  ${links.map((link) => id('role_permission', linkKey(link.role, link.permission))).join(',\n  ')}\n);`,
    `DELETE FROM "public"."roles" WHERE "key" IN (\n  ${keyList(roles.map((role) => role.key))}\n);`,
    `DELETE FROM "public"."permissions" WHERE "key" IN (\n  ${keyList(catalogue.map((permission) => permission.key))}\n);`,
    '',
  ].join('\n');
  return { up, down };
}
